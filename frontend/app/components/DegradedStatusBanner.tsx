/**
 * Prominent status banner displayed when `degraded: true` is returned by `/api/scan`,
 * clearly indicating which fallback layer generated the diagnostic response.
 */
export default function DegradedStatusBanner({
  degraded,
  servedBy,
  language = "en",
}: DegradedStatusBannerProps) {
  const isTa = language === "ta";

  if (!degraded) {
    const isCache = servedBy === "cache";
    return (
      <div
        id="pipeline-layer-banner"
        data-testid="pipeline-layer-banner"
        role="status"
        aria-live="polite"
        className="flex flex-wrap items-center justify-between gap-2 rounded-2xl border border-emerald-200 bg-emerald-50/70 px-4 py-3 text-xs font-semibold text-emerald-900 shadow-xs"
      >
        <div className="flex items-center gap-2">
          <span aria-hidden="true">{isCache ? "⚡" : "✨"}</span>
          <span>
            {isCache
              ? isTa
                ? "சரிபார்க்கப்பட்ட தற்காலிக சேமிப்பிலிருந்து உடனடியாக வழங்கப்பட்டது (Instant Verified Cache)"
                : "Served instantly from verified Layer 0 cache"
              : isTa
              ? "முதன்மை AI மூலம் சரிபார்க்கப்பட்டது (Primary Cloud AI)"
              : "Generated via primary cloud AI (Layer 1 · Gemini)"}
          </span>
        </div>
        <span className="rounded-lg bg-emerald-200/70 px-2.5 py-1 font-mono text-[11px] font-bold text-emerald-950">
          served_by: {servedBy}
        </span>
      </div>
    );
  }

  const meta = FALLBACK_LAYER_META[servedBy] ?? DEFAULT_DEGRADED_META;

  return (
    <div
      id="degraded-status-banner"
      data-testid="degraded-status-banner"
      role="alert"
      aria-live="assertive"
      className="flex flex-col gap-2.5 rounded-2xl border-2 border-amber-400 bg-gradient-to-r from-amber-50 via-orange-50/70 to-amber-50 p-4 text-amber-950 shadow-sm"
    >
      <div className="flex flex-wrap items-center justify-between gap-2">
        <div className="flex items-center gap-2.5">
          <span className="text-lg" aria-hidden="true">
            {meta.icon}
          </span>
          <div className="flex flex-col">
            <span className="text-[11px] font-extrabold uppercase tracking-wider text-amber-800">
              {isTa ? "மாற்று காப்புப் பாதை (Degraded Fallback Mode)" : "Degraded Fallback Mode Active"}
            </span>
            <p className="text-sm font-extrabold text-amber-950 sm:text-base">
              {isTa ? meta.headlineTa : meta.headline}
            </p>
          </div>
        </div>

        <div className="flex items-center gap-1.5 self-start sm:self-center">
          <span className="rounded-lg border border-amber-300 bg-amber-200/80 px-2.5 py-1 text-[11px] font-bold uppercase tracking-wide text-amber-950">
            {meta.layerTag}
          </span>
          <code className="rounded-lg border border-amber-300 bg-white/90 px-2 py-1 font-mono text-[11px] font-bold text-amber-900">
            served_by: {servedBy}
          </code>
        </div>
      </div>

      <p className="text-xs font-medium leading-relaxed text-amber-900">
        {isTa ? meta.descriptionTa : meta.description}
      </p>
    </div>
  );
}
